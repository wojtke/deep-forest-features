"""Fidelity check: the official DF21 package (deep-forest 0.1.7) vs our base cascade.

DF21 0.1.7 ships wheels only for Python <= 3.9 on x86_64, so it runs in its own environment
(on Apple Silicon through Rosetta). Our cascade differs by design: 3-fold OOF instead of
out-of-bag predictions and balanced accuracy instead of accuracy for the depth rule, so the
scores should be close, not equal. Steps (from the repo root):

  uv run python scripts/check_df21.py export spambase vehicle abalone wine_red
  uv run --no-project --python cpython-3.9-macos-x86_64 --with deep-forest==0.1.7 \
      --with scikit-learn==1.0.2 --with "numpy<1.24" --with "scipy<1.10" \
      python scripts/check_df21.py fit
  uv run dfx run main --methods base --seeds 0 --datasets spambase,vehicle,abalone,wine_red
  uv run python scripts/check_df21.py compare      # writes docs/df21-check.md

The `fit` step imports nothing from this repo and keeps Python 3.9 syntax.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FOLDER = ROOT / "data" / "df21"
SEED = 0


def export(names):
    import numpy as np

    from dfx.data import load, outer_folds
    from dfx.prep import Preprocessor

    FOLDER.mkdir(parents=True, exist_ok=True)
    for name in names:
        data = load(name)
        folds, _ = outer_folds(data, SEED, 5)
        for k in range(5):
            train, test = np.flatnonzero(folds != k), np.flatnonzero(folds == k)
            prep = Preprocessor().fit(data.X[train], data.categorical)
            np.savez(FOLDER / f"{name}-f{k}.npz", x_tr=prep.transform(data.X[train]), y_tr=data.y[train],
                     x_te=prep.transform(data.X[test]), y_te=data.y[test], task=data.task)
        print(f"exported {name}")


def fit():
    import numpy as np
    from deepforest import CascadeForestClassifier, CascadeForestRegressor
    from sklearn.metrics import balanced_accuracy_score

    out = {}
    for path in sorted(FOLDER.glob("*-f*.npz")):
        z = np.load(path)
        classification = str(z["task"]) == "classification"
        model = (CascadeForestClassifier if classification else CascadeForestRegressor)(random_state=SEED, verbose=0)
        model.fit(z["x_tr"], z["y_tr"])  # DF21 defaults
        pred = model.predict(z["x_te"])
        score = (balanced_accuracy_score(z["y_te"], pred) if classification
                 else float(np.sqrt(np.mean((z["y_te"] - np.ravel(pred)) ** 2))))
        out[path.stem] = {"score": float(score), "layers": int(model.n_layers_)}
        print(path.stem, out[path.stem], flush=True)
    (FOLDER / "df21-results.json").write_text(json.dumps(out, indent=1) + "\n")


def compare():
    import numpy as np

    df21 = json.loads((FOLDER / "df21-results.json").read_text())
    rows = ["| dataset | metric | DF21 0.1.7 | ours (base cascade) | DF21 layers kept | our best layer |", "|---|---|---|---|---|---|"]
    names = sorted({k.rsplit("-f", 1)[0] for k in df21})
    for name in names:
        theirs, ours, l1, l2 = [], [], [], []
        for k in range(5):
            r = json.loads((ROOT / "results" / "main" / "default" / name / "base" / f"s{SEED}-f{k}.json").read_text())
            metric = "balanced_accuracy" if r["task_type"] == "classification" else "rmse"
            ours.append(r["metrics"][metric])
            l2.append(r["best_layer"])
            theirs.append(df21[f"{name}-f{k}"]["score"])
            l1.append(df21[f"{name}-f{k}"]["layers"])
        rows.append(f"| {name} | {metric} | {np.mean(theirs):.4f} ± {np.std(theirs, ddof=1):.4f} | "
                    f"{np.mean(ours):.4f} ± {np.std(ours, ddof=1):.4f} | {np.mean(l1):.1f} | {np.mean(l2):.1f} |")
    text = ("# DF21 fidelity check\n\nGenerated by `scripts/check_df21.py`: seed 0, the same 5 outer folds and "
            "preprocessing; mean ± sd over folds. Differences by design: 3-fold OOF vs out-of-bag layer "
            "predictions, and balanced accuracy vs accuracy in the depth rule. Layers: DF21 keeps layers up to "
            "the best one; ours is the best layer.\n\n" + "\n".join(rows) + "\n")
    (ROOT / "docs" / "df21-check.md").write_text(text)
    print(text)


if __name__ == "__main__":
    command, args = sys.argv[1], sys.argv[2:]
    {"export": lambda: export(args), "fit": fit, "compare": compare}[command]()
